# int possible type conversions
a1 = 3.4  # float value
print(a1,type(a1))
b1 = int(a1)  # float converted into int value
print(b1,type(b1))

a = True  # bool value
print(a,type(a)) 
b = int(a)   # int value
print(b,type(b)) 

A = "50" # string  value
print(A,type(A))
B = int(A)
print(B,type(B))