# Bitwise AND Operator
a = 6
b = 5

print(a & b)

# Bitwise OR Operator
a = 5
b = 3

print(a | b)

# Bitwise XOR Operator
a = 7
b = 5

print(a ^ b)

# Bitwise NOT Operator
a = 8

print(~a)

#Left Shift << → Multiply by 2 for each shift.
a = 10
b = 4
print(a << 1)
print(b << 2)



#Right Shift >> → Divide by 2 for each shift
a = 10
b = 4
print(a >> 2)
print(a >> b) 