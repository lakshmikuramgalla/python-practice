# Float Type Conversions
a = 10  # int
print(a,type(a)) 
b = float(a) # Float 
print(b,type(b)) 

A = False
print(A,type(A))
B = float(A)
print(B,type(B))

a1 = "10"
print(a1,type(a1)) 
b1 = float(a1)
print(b1,type(b1)) 

A1 = "11.5"
print(A1,type(A1)) 
B1 = float(A1)
print(B1,type(B1)) 